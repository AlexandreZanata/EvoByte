def build_all_packages(
    audit_path: Path = DEFAULT_AUDIT_PATH,
    out_dir: Path = DEFAULT_OUT_DIR,
    index_path: Path = DEFAULT_INDEX_PATH,
) -> dict[str, Any]:
    """Generate all curator packages and emit tracking index."""
    out_dir.mkdir(parents=True, exist_ok=True)
    index_path.parent.mkdir(parents=True, exist_ok=True)

    pkg_gordon = generate_dan_gordon_package(out_dir)
    pkg_grassl = generate_markus_grassl_package(out_dir)
    pkg_sloane = generate_neil_sloane_package(out_dir)

    index_data = {
        "index_version": "2.0.0",
        "created_at": "2026-10-26T17:35:00Z",
        "audit_reference": str(
            audit_path.relative_to(REPO_ROOT)
            if audit_path.is_relative_to(REPO_ROOT)
            else audit_path
        ),
        "overall_campaign_verdict": "DISCOVERY_TIED",
        "curator_packages": {
            "dan_gordon_ljcr": pkg_gordon,
            "markus_grassl_codetables": pkg_grassl,
            "neil_sloane_oeis": pkg_sloane,
        },
        "safety_guarantee": {
            "autonomous_emails_sent": 0,
            "external_api_calls": 0,
            "human_submission_status": "pending_human_submission",
            "corresponding_author": "Alexandre Zanata",
        },
    }

    formatted = json.dumps(index_data, sort_keys=True, indent=2) + "\n"
    index_path.write_text(formatted, encoding="utf-8")
    print(f"[+] Successfully generated 3 curator packages in {out_dir}")
    print(f"[+] Wrote index to {index_path}")
    return index_data


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Build P199 Curator Packages")
    parser.add_argument("--audit-path", type=Path, default=DEFAULT_AUDIT_PATH)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--index-path", type=Path, default=DEFAULT_INDEX_PATH)
    args = parser.parse_args(argv[1:])

    build_all_packages(audit_path=args.audit_path, out_dir=args.out_dir, index_path=args.index_path)
    return 0


